use rustshark_shared::Lang;

pub fn t(lang: Lang, key: &'static str) -> &'static str {
    match pair(key) {
        Some((fr, en)) => lang.pick(fr, en),
        None => key,
    }
}

pub fn t_dyn(lang: Lang, key: &str) -> &'static str {
    pair(key).map(|(fr, en)| lang.pick(fr, en)).unwrap_or("")
}

